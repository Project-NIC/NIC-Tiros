"""NIC-Tiros — what the contact's magnets do to the magnetometer. Run: python3 calc/magnet.py
A dipole sketch: one magnet, and the Belka-like pair of opposite poles. Writes calc/out/magnet.md."""
import math, os
import params as p

mu0 = 4e-7 * math.pi
vol = math.pi * (p.MAGNET_D_MM / 2000) ** 2 * (p.MAGNET_H_MM / 1000)
m = p.MAGNET_BR_T * vol / mu0                      # A·m²
def b_axis(r):                                     # on the axis of one dipole, tesla
    return mu0 / (4 * math.pi) * 2 * m / r ** 3
rows = []
for d in p.MAG_DISTANCE_MM:
    r = d / 1000
    one = b_axis(r) * 1e6
    g = p.MAGNET_PAIR_GAP_MM / 1000                # the pair along a line, the sensor beyond one end
    pair = (b_axis(r) - b_axis(r + g)) * 1e6
    drift = pair * abs(p.MAGNET_TEMPCO) * p.TEMP_SWING_K
    head = math.degrees(math.atan(drift / p.EARTH_FIELD_UT))
    flag = "SATURATES" if pair > p.MAG_RANGE_UT else "in range"
    rows.append((f"{d} mm", f"{one:.0f} µT", f"{pair:.0f} µT ({pair/p.EARTH_FIELD_UT:.1f}× the Earth's), {flag}",
                 f"{drift:.2f} µT → up to {head:.1f}°"))
md = ["# NIC-Tiros — the contact's magnets and the magnetometer", "",
      f"Generated by `calc/magnet.py`; an assumed magnet Ø {p.MAGNET_D_MM} × {p.MAGNET_H_MM} mm. "
      f"A fixed offset is calibrated out; its drift with {p.TEMP_SWING_K} K is not.", "",
      "| distance | one magnet | the pair, opposite poles | drift over the swing → heading |", "|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "out", "magnet.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))

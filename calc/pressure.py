"""NIC-Tiros, level 4 — the pressure port and the apogee. Run: python3 calc/pressure.py
Writes calc/out/pressure.md and calc/out/apogee.svg. A rough sketch: every rocket differs.
"""
import math, os, random
import params as p

here = os.path.dirname(os.path.abspath(__file__))
rows = []
# 1. the port's lag: laminar flow through a short hole into a chamber (Poiseuille, isothermal)
for d in p.PORT_D_MM:
    for v in p.CHAMBER_CM3:
        r = d / 2000
        tau = 8 * p.AIR_VISCOSITY * (p.PORT_L_MM / 1000) * (v * 1e-6) / (math.pi * r ** 4 * p.AIR_PRESSURE)
        rows.append(("port lag", f"hole Ø {d} mm, chamber {v} cm³", f"{tau*1000:.3f} ms"))
# 2. how flat the pressure is round the apogee: h = h0 − g t²/2
for t in (0.25, 0.5, 1.0):
    dh = p.G * t * t / 2
    dp = p.AIR_PRESSURE * dh / p.SCALE_HEIGHT_M
    rows.append(("apogee", f"±{t} s from the top", f"{dh:.2f} m lower, {dp:.1f} Pa more — "
                 f"{dp/p.BARO_NOISE_PA:.0f}× the noise"))
os.makedirs(os.path.join(here, "out"), exist_ok=True)
md = ["# NIC-Tiros — the pressure port and the apogee", "",
      "Generated by `calc/pressure.py`; never edited by hand. A sketch: each rocket differs.", "",
      "| | what | value |", "|---|---|---|"] + [f"| {a} | {b} | {c} |" for a, b, c in rows]
open(os.path.join(here, "out", "pressure.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))

# a small picture: the height near the top, as the barometer sees it with its noise
random.seed(1)
W, H, T = 560, 260, 3.0
pts, noisy = [], []
for i in range(121):
    t = -T + 2 * T * i / 120
    h = -p.G * t * t / 2
    pts.append((t, h))
    noisy.append((t, h + random.gauss(0, p.BARO_NOISE_PA * p.SCALE_HEIGHT_M / p.AIR_PRESSURE)))
hmin = min(h for _, h in pts) - 2
X = lambda t: 40 + (t + T) / (2 * T) * (W - 60)
Y = lambda h: 20 + (0 - h) / (0 - hmin) * (H - 60)
path = " ".join(f"{'M' if i == 0 else 'L'}{X(t):.1f},{Y(h):.1f}" for i, (t, h) in enumerate(pts))
dots = "".join(f'<circle cx="{X(t):.1f}" cy="{Y(h):.1f}" r="1.6" fill="#888"/>' for t, h in noisy)
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" font-family="sans-serif" font-size="12">
<rect width="100%" height="100%" fill="white"/>
<line x1="40" y1="{Y(0):.1f}" x2="{W-20}" y2="{Y(0):.1f}" stroke="#ccc"/>
<line x1="{X(0):.1f}" y1="10" x2="{X(0):.1f}" y2="{H-40}" stroke="#c33" stroke-dasharray="4 3"/>
{dots}<path d="{path}" fill="none" stroke="#1f5fbf" stroke-width="2"/>
<text x="{X(0)+6:.1f}" y="22" fill="#c33">the top (apogee)</text>
<text x="44" y="{H-14}">−{T:.0f} s</text><text x="{W-50}" y="{H-14}">+{T:.0f} s</text>
<text x="{W/2-130:.0f}" y="{H-14}">height near the top; dots: as a barometer with ~{p.BARO_NOISE_PA:.0f} Pa noise sees it</text>
<text x="44" y="{Y(hmin)+4:.1f}">{hmin:.0f} m</text>
</svg>'''
open(os.path.join(here, "out", "apogee.svg"), "w").write(svg)
